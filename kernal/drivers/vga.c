/* ── Textmodus-Helfer ───────────────────────────────────────────── */
static void update_cursor(void)
{
    uint16_t pos = (uint16_t)(cur_row * VGA_WIDTH + cur_col);
    outb(VGA_CRTC_ADDR, VGA_CURSOR_HI);
    outb(VGA_CRTC_DATA, (uint8_t)(pos >> 8));
    outb(VGA_CRTC_ADDR, VGA_CURSOR_LO);
    outb(VGA_CRTC_DATA, (uint8_t)(pos & 0xFF));
}

static void scroll(void)
{
    volatile uint16_t *vmem = VGA_MEMORY;
    for (int row = 1; row < VGA_HEIGHT; row++)
        for (int col = 0; col < VGA_WIDTH; col++)
            vmem[(row - 1) * VGA_WIDTH + col] = vmem[row * VGA_WIDTH + col];

    for (int col = 0; col < VGA_WIDTH; col++)
        vmem[(VGA_HEIGHT - 1) * VGA_WIDTH + col] =
            vga_make_entry(' ', vga_make_attr(VGA_LIGHT_GREY, VGA_BLACK));

    cur_row = VGA_HEIGHT - 1;
}

/* ── Öffentlich: Textmodus-API ───────────────────────────────────── */
void vga_init(void)
{
    cur_attr = vga_make_attr(VGA_LIGHT_GREY, VGA_BLACK);
    vga_clear();
}

void vga_clear(void)
{
    volatile uint16_t *vmem = VGA_MEMORY;
    for (int i = 0; i < VGA_WIDTH * VGA_HEIGHT; i++)
        vmem[i] = vga_make_entry(' ', cur_attr);
    cur_col = cur_row = 0;
    update_cursor();
}

void vga_set_fg(vga_color_t c) { cur_attr = (cur_attr & 0xF0) | (c & 0x0F); }
void vga_set_bg(vga_color_t c) { cur_attr = (uint8_t)((cur_attr & 0x0F) | ((c & 0x0F) << 4)); }
void vga_set_color(vga_color_t fg, vga_color_t bg) { cur_attr = vga_make_attr(fg, bg); }
uint8_t vga_get_col(void) { return cur_col; }
uint8_t vga_get_row(void) { return cur_row; }

void vga_set_cursor(uint8_t col, uint8_t row)
{
    cur_col = (col < VGA_WIDTH)  ? col : VGA_WIDTH  - 1;
    cur_row = (row < VGA_HEIGHT) ? row : VGA_HEIGHT - 1;
    update_cursor();
}

void vga_putchar(char c)
{
    volatile uint16_t *vmem = VGA_MEMORY;

    switch (c) {
    case '\n':
        cur_col = 0;
        cur_row++;
        break;
    case '\r':
        cur_col = 0;
        break;
    case '\t':
        cur_col = (uint8_t)((cur_col + 4) & ~3);
        if (cur_col >= VGA_WIDTH) { cur_col = 0; cur_row++; }
        break;
    case '\b':
        if (cur_col > 0) {
            cur_col--;
            vmem[cur_row * VGA_WIDTH + cur_col] = vga_make_entry(' ', cur_attr);
        }
        break;
    default:
        vmem[cur_row * VGA_WIDTH + cur_col] = vga_make_entry(c, cur_attr);
        cur_col++;
        if (cur_col >= VGA_WIDTH) { cur_col = 0; cur_row++; }
        break;
    }

    if (cur_row >= VGA_HEIGHT) scroll();
    update_cursor();
}

void vga_puts(const char *str)
{
    while (*str) vga_putchar(*str++);
}

void vga_printf(const char *fmt, ...)
{
    char buf[512];
    __builtin_va_list ap;
    __builtin_va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    __builtin_va_end(ap);
    vga_puts(buf);
}

/* ── Framebuffer-Implementierung ─────────────────────────────────── */
bool fb_init(multiboot_info_t *mbi)
{
    if (!(mbi->flags & MULTIBOOT_INFO_FB)) return false;
    if (mbi->framebuffer_type != 2) return false;   /* Muss RGB sein */
    if (mbi->framebuffer_bpp  != 32) return false;  /* Nur 32 bpp */

    fb_addr   = (uint32_t)mbi->framebuffer_addr;
    fb_pitch  = mbi->framebuffer_pitch;
    fb_width  = mbi->framebuffer_width;
    fb_height = mbi->framebuffer_height;
    fb_bpp    = mbi->framebuffer_bpp;
    fb_active = true;
    return true;
}

void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (!fb_active || x >= fb_width || y >= fb_height) return;
    uint32_t *pixel = (uint32_t *)(fb_addr + y * fb_pitch + x * (fb_bpp / 8));
    *pixel = color;
}

void fb_clear(uint32_t color)
{
    if (!fb_active) return;
    for (uint32_t y = 0; y < fb_height; y++)
        for (uint32_t x = 0; x < fb_width; x++)
            fb_put_pixel(x, y, color);
}

void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t row = y; row < y + h && row < fb_height; row++)
        for (uint32_t col = x; col < x + w && col < fb_width; col++)
            fb_put_pixel(col, row, color);
}

void fb_put_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg)
{
    if (!fb_active) return;
    uint8_t idx = (uint8_t)c;
    if (idx < 32 || idx > 127) idx = '?';
    const uint8_t *glyph = font8x8[idx - 32];

    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            uint32_t color = (glyph[row] & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + (uint32_t)col, y + (uint32_t)row, color);
        }
    }
}

void fb_puts(uint32_t x, uint32_t y, const char *str, uint32_t fg, uint32_t bg)
{
    uint32_t cx = x;
    while (*str) {
        if (*str == '\n') { cx = x; y += 8; }
        else { fb_put_char(cx, y, *str, fg, bg); cx += 8; }
        str++;
    }
}
